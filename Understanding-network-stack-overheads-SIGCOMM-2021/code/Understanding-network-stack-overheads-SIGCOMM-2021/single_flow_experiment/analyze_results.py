#!/usr/bin/env python3
"""Analyze recorded iperf3 JSON without changing or fabricating measurements."""
import argparse
import csv
import json
import math
import statistics
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt


def mean(v):
    return statistics.mean(v) if v else float('nan')


def get(d, path, default=None):
    for key in path:
        if not isinstance(d, dict):
            return default
        d = d.get(key)
        if d is None:
            return default
    return d


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--input', type=Path, default=Path('results'), help='Directory with run_N.json files')
    p.add_argument('--out', type=Path, default=None, help='Directory for summary and graphs')
    args = p.parse_args()
    source = args.input
    out = args.out or (source / 'paper_style_charts')
    out.mkdir(parents=True, exist_ok=True)
    files = sorted(source.glob('run_*.json'), key=lambda path: int(path.stem.split('_')[-1]))
    if not files:
        raise SystemExit(f'No run_N.json measurements in {source}')
    records = []
    intervals = []
    for file in files:
        run = int(file.stem.split('_')[-1])
        d = json.loads(file.read_text())
        received = get(d, ['end','sum_received','bits_per_second'])
        cpu = get(d, ['end','cpu_utilization_percent'], {})
        if received is None:
            print('Skipping incomplete measurement', file)
            continue
        row = dict(run=run, throughput_gbps=received/1e9,
                   sender_cpu=cpu.get('host_total'), receiver_cpu=cpu.get('remote_total'),
                   sender_user=cpu.get('host_user'), sender_system=cpu.get('host_system'),
                   receiver_user=cpu.get('remote_user'), receiver_system=cpu.get('remote_system'),
                   retransmits=get(d, ['end','sum_sent','retransmits'], 0),
                   vm_cpu_pct=None, vm_cores=None, gbps_per_utilized_vcpu=None)
        records.append(row)
        for item in d.get('intervals', []):
            stream = get(item, ['sum'], {})
            rate = stream.get('bits_per_second')
            second = stream.get('start')
            if rate is not None and second is not None:
                intervals.append((run, float(second), rate/1e9))
    # Additional guest-wide CPU measurements exist only in sessions generated by run_vm.py.
    session_csv = source / 'session_results.csv'
    if session_csv.exists():
        with session_csv.open(newline='') as f:
            by_run = {int(v['Run']): v for v in csv.DictReader(f)}
        for row in records:
            v = by_run.get(row['run'])
            if v and v.get('VM_CPU_percent'):
                row['vm_cpu_pct'] = float(v['VM_CPU_percent'])
                row['vm_cores'] = float(v['Utilized_vCPUs'])
                row['gbps_per_utilized_vcpu'] = float(v['Gbps_per_utilized_vCPU'])
    if not records:
        raise SystemExit('No valid measurements')

    # Heuristic quality flag: don't delete results based on a guess.
    receiver_valid = [v['receiver_cpu'] for v in records if v['receiver_cpu'] is not None]
    median_receiver = statistics.median(receiver_valid) if receiver_valid else None
    for row in records:
        r = row['receiver_cpu']
        row['cpu_quality_note'] = ('check_low_receiver_cpu' if median_receiver and r is not None
                                   and r < 0.2 * median_receiver else '')
    columns = ['run','throughput_gbps','sender_cpu','receiver_cpu','sender_user','sender_system',
               'receiver_user','receiver_system','retransmits','vm_cpu_pct','vm_cores',
               'gbps_per_utilized_vcpu','cpu_quality_note']
    with (out/'measurements_reviewed.csv').open('w', newline='') as f:
        w=csv.DictWriter(f,fieldnames=columns); w.writeheader(); w.writerows(records)
    x=[r['run'] for r in records]
    y=[r['throughput_gbps'] for r in records]
    plt.figure(figsize=(11,4.8)); plt.plot(x,y,marker='o',markersize=3,linewidth=1)
    plt.axhline(mean(y),linestyle='--',color='black',label=f'Mean {mean(y):.2f} Gbps')
    plt.xlabel('Run number'); plt.ylabel('Receiver goodput (Gbps)'); plt.title('Single TCP flow: repeatability over loopback')
    plt.legend(); plt.grid(alpha=.25); plt.tight_layout(); plt.savefig(out/'01_throughput_by_run.png',dpi=180); plt.close()

    plt.figure(figsize=(9,4.8)); plt.hist(y,bins=min(12,max(4,int(math.sqrt(len(y))))),edgecolor='white')
    plt.axvline(mean(y),linestyle='--',color='black',label=f'Mean {mean(y):.2f} Gbps')
    plt.xlabel('Receiver goodput (Gbps)'); plt.ylabel('Number of runs'); plt.title('Distribution of measured goodput')
    plt.legend(); plt.tight_layout(); plt.savefig(out/'02_throughput_distribution.png',dpi=180); plt.close()

    plt.figure(figsize=(11,4.8)); plt.plot(x,[r['sender_cpu'] for r in records],label='Sender process',linewidth=1.4)
    plt.plot(x,[r['receiver_cpu'] for r in records],label='Receiver process',linewidth=1.4)
    for row in records:
        if row['cpu_quality_note']:
            plt.scatter(row['run'],row['receiver_cpu'],marker='x',s=75,color='red',zorder=5)
    plt.xlabel('Run number');plt.ylabel('iPerf3 process CPU (% of one logical CPU)')
    plt.title('Related to Fig. 3(b): endpoint process CPU, not whole-host CPU')
    plt.grid(alpha=.25);plt.legend();plt.tight_layout();plt.savefig(out/'03_sender_receiver_cpu.png',dpi=180);plt.close()

    # Separate stacks, normalized fractions of measured user+system CPU time.
    labels=['Sender','Receiver']
    total_user=[mean([r[k] for r in records if r[k] is not None]) for k in ['sender_user','receiver_user']]
    total_system=[mean([r[k] for r in records if r[k] is not None]) for k in ['sender_system','receiver_system']]
    plt.figure(figsize=(7,4.8));plt.bar(labels,total_user,label='User mode')
    plt.bar(labels,total_system,bottom=total_user,label='System mode')
    plt.ylabel('Mean reported process CPU (% of one logical CPU)')
    plt.title('Related to Fig. 3(c–d): mode breakdown only')
    plt.legend();plt.grid(axis='y',alpha=.25);plt.tight_layout();plt.savefig(out/'04_user_system_cpu.png',dpi=180);plt.close()

    plt.figure(figsize=(11,4.8));plt.bar(x,[r['retransmits'] or 0 for r in records])
    plt.xlabel('Run number');plt.ylabel('Sender-reported TCP retransmits')
    plt.title('TCP retransmissions on loopback (not physical packet loss)')
    plt.tight_layout();plt.savefig(out/'05_retransmissions.png',dpi=180);plt.close()

    if intervals:
        # Plot per-second goodput for select actual runs, avoiding an illegible 50-trace plot.
        chosen=list(dict.fromkeys([records[0]['run'],records[len(records)//2]['run'],records[-1]['run']]))
        plt.figure(figsize=(10,4.8))
        for run in chosen:
            pts=sorted((s,b) for r,s,b in intervals if r==run)
            if pts:
                plt.plot([s for s,b in pts],[b for s,b in pts],label=f'Run {run}')
        plt.xlabel('Time within run (seconds)');plt.ylabel('Reported interval goodput (Gbps)')
        plt.title('Throughput during selected runs');plt.grid(alpha=.25);plt.legend();plt.tight_layout()
        plt.savefig(out/'06_interval_throughput.png',dpi=180);plt.close()

    cpu_rows=[r for r in records if r['gbps_per_utilized_vcpu'] is not None]
    if cpu_rows:
        plt.figure(figsize=(10,4.8))
        plt.bar([str(r['run']) for r in cpu_rows],[r['gbps_per_utilized_vcpu'] for r in cpu_rows])
        plt.xlabel('Run');plt.ylabel('Gbps / utilized guest vCPU')
        plt.title('Related to Fig. 3(a): VM-wide CPU efficiency (includes both endpoints)')
        plt.grid(axis='y',alpha=.25);plt.tight_layout();plt.savefig(out/'07_vm_cpu_efficiency.png',dpi=180);plt.close()
    summary = {
        'source':str(source), 'runs':len(records),
        'mean_gbps':mean(y), 'median_gbps':statistics.median(y),
        'stddev_gbps':statistics.stdev(y) if len(y)>1 else 0,
        'min_gbps':min(y),'max_gbps':max(y),
        'mean_sender_process_cpu_pct':mean([r['sender_cpu'] for r in records if r['sender_cpu'] is not None]),
        'mean_receiver_process_cpu_pct_including_flags':mean(receiver_valid),
        'receiver_cpu_values_flagged':[(r['run'],r['receiver_cpu']) for r in records if r['cpu_quality_note']],
        'cpu_efficiency_measured':bool(cpu_rows),
        'explanation':'Not a physical 100Gbps NIC result. Process CPU and guest-wide CPU are different metrics.'
    }
    (out/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
    print(json.dumps(summary,indent=2))
    print('Charts saved in',out)

if __name__=='__main__':
    main()
